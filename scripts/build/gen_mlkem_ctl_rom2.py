#!/usr/bin/env python3
"""scripts/build/gen_mlkem_ctl_rom2.py

Phase 9F S1b (evidence/phase9m/batch1/9f1b/test_plan_9f1b.md V2): generates rtl/mlkem/mlkem_ctl_rom2.sv from the golden model tb/golden/mlkem_ctl_model2.py (programs with the background hash job); same flow as scripts/build/gen_mlkem_ctl_rom.py (never hand-typed): the micro-programs of KeyGen (0), Encaps (1) and
Decaps (2), one 40-bit word per micro-operation, followed by END. The file carries no date, so re-running reproduces it byte for byte; --check compares instead of writing (exit 1 on a difference) and runs the static checks of the model.
Usage: python3 scripts/build/gen_mlkem_ctl_rom2.py [--check]
"""
from __future__ import annotations

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tb" / "golden"))

import mlkem_ctl_model2 as CM  # noqa: E402

OUT = ROOT / "rtl" / "mlkem" / "mlkem_ctl_rom2.sv"
PW = 6


def sv() -> str:
    CM.check_static2()
    lines = []
    for name, pid in CM.PROG_ID.items():
        prog = CM.PROGRAMS2[name]
        assert len(prog) <= 2 ** PW
        for pc, op in enumerate(prog):
            lines.append(f"      {{2'd{pid}, {PW}'d{pc}}}: word_o = 40'h{CM.encode(op):010x};   // {name} {pc}: {' '.join(str(x) for x in op)}")
    body = "\n".join(lines)
    return f"""`default_nettype none
`timescale 1ns/1ps
// rtl/mlkem/mlkem_ctl_rom2.sv
// GENERATED by scripts/build/gen_mlkem_ctl_rom2.py from tb/golden/mlkem_ctl_model2.py. Do not hand-edit.
// Micro-instruction word [39:0]: opc[39:36] 0 END, 1 LDP, 2 STP, 3 HST, 4 HFD, 5 HGT, 6 SDL, 7 RUN, 8 WR32, 9 RD32, 10 CMP, 11 BGS, 12 JN.
//   BGS: job start word[35:30] (the job words HST, HFD..., HGT, END follow the main program END)   JN: no field (waits for the background hash job).
//   LDP / STP: slot[35:32] region[31:30] word offset[29:21] dsel[20:19] (0: d = 1, 1: 4, 2: 10, 3: 12)
//   HST: sel[35:34] (0 H, 1 G, 2 J) length in bytes[33:23]      HFD: source[35:33] (0 KB, 1 CB, 2 CB2, 3 RF, 4 constant word 0x03) word offset[32:24] words[23:15]
//   HGT: dstA[35:33] dstB[32:30] (register numbers)             RUN: engine program[35:34]      WR32 / RD32: register[35:33] KB word offset[32:24]
// Programs (op_i): 0 KeyGen, 1 Encaps, 2 Decaps. Straight-line main code ending with END, then the words of one background hash job (also straight-line, ending with END). Unlisted addresses return END.

module mlkem_ctl_rom2 (
    input  wire  [1:0]  op_i,
    input  wire  [{PW-1}:0]  pc_i,
    output logic [39:0] word_o
);

  always_comb begin
    case ({{op_i, pc_i}})
{body}
      default: word_o = 40'd0;
    endcase
  end

endmodule
`default_nettype wire
"""


def main():
    text = sv()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("DIFFERENT: rtl/mlkem/mlkem_ctl_rom2.sv does not match the model")
            return 1
        print("rtl/mlkem/mlkem_ctl_rom2.sv equals the generated ROM; static checks passed")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}: " + ", ".join(f"{n} {len(p)} ops" for n, p in CM.PROGRAMS2.items()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
