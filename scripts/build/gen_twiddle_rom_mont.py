#!/usr/bin/env python3
"""scripts/build/gen_twiddle_rom_mont.py

Phase 5b (evidence/phase05/test_plan.md section 3, ADR 0011): generates rtl/arith/twiddle_rom_mont.sv,
the twiddle ROM in Montgomery form for rtl/arith/modmul_montgomery.sv (R = 2^12), from the verified golden model
(tb/golden/primitives.py's _ZETA_BITREV and _GAMMA tables) -- never hand-typed, same layout and ports as the frozen
rtl/ntt/twiddle_rom.sv (generated by scripts/build/gen_twiddle_rom.py).

ROM_ZETA_M[i]  = ROM_ZETA[i]  * R mod q
ROM_GAMMA_M[i] = ROM_GAMMA[i] * R mod q
A Montgomery product mont(x, ROM_ZETA_M[i]) = x * ROM_ZETA[i] mod q, so the butterfly's function is unchanged.
The file carries no date, so re-running the generator reproduces it byte for byte (checked by tb/arith/check_mont_rom.py).

Run: python3 scripts/build/gen_twiddle_rom_mont.py
"""

from __future__ import annotations

import pathlib
import sys

REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT / "tb" / "golden"))

from params import N, Q, ZETA  # noqa: E402
from primitives import _GAMMA, _ZETA_BITREV  # noqa: E402

R = 1 << 12
OUT = REPO_ROOT / "rtl" / "arith" / "twiddle_rom_mont.sv"

assert len(_ZETA_BITREV) == 128 and len(_GAMMA) == 128
zeta_m = [(v * R) % Q for v in _ZETA_BITREV]
gamma_m = [(v * R) % Q for v in _GAMMA]


def rom_body(sig: str, values: list[int]) -> str:
    return "\n".join(f"    {sig}[{i}] = 12'd{v};" for i, v in enumerate(values))


def render() -> str:
    return f"""`default_nettype none
`timescale 1ns/1ps
// rtl/arith/twiddle_rom_mont.sv
// GENERATED by scripts/build/gen_twiddle_rom_mont.py from tb/golden/primitives.py (ZETA={ZETA}, Q={Q}, N={N}, R=2^12).
// Do not hand-edit; re-run the generator instead.
//
// Montgomery form of rtl/ntt/twiddle_rom.sv for rtl/arith/modmul_montgomery.sv:
//   ROM_ZETA_M[i]  = (zeta^BitRev7(i) mod q)       * 2^12 mod q
//   ROM_GAMMA_M[i] = (zeta^(2*BitRev7(i)+1) mod q) * 2^12 mod q
// Same ports and addressing as rtl/ntt/twiddle_rom.sv.

module twiddle_rom_mont (
    input  wire [6:0]  addr_i,       // 0..127
    output logic [11:0] zeta_o,      // ROM_ZETA_M[addr_i]
    output logic [11:0] gamma_o      // ROM_GAMMA_M[addr_i]
);

  logic [11:0] rom_zeta [0:127];
  logic [11:0] rom_gamma [0:127];

  initial begin
{rom_body("rom_zeta", zeta_m)}
{rom_body("rom_gamma", gamma_m)}
  end

  assign zeta_o  = rom_zeta[addr_i];
  assign gamma_o = rom_gamma[addr_i];

endmodule
`default_nettype wire
"""


if __name__ == "__main__":
    OUT.write_text(render())
    print(f"wrote {OUT.relative_to(REPO_ROOT)} ({len(zeta_m)} zeta + {len(gamma_m)} gamma entries, Montgomery form)")
