#!/usr/bin/env python3
"""scripts/build/gen_twiddle_rom.py

Generates rtl/ntt/twiddle_rom.sv from the verified golden model
(tb/golden/primitives.py's _ZETA_BITREV and _GAMMA tables), so the RTL ROM contents are never
hand-typed (docs/ROADMAP.md Phase 1 scope: "twiddle ROM generated by a script from the golden
model, never hand-typed").

ROM_ZETA[i]  = zeta^BitRev7(i)   mod q, for i = 0..127  (Algorithms 9/10; i=0 is the Appendix A
               entry, value 1, unused by the butterfly FSM but included for completeness).
ROM_GAMMA[i] = zeta^(2*BitRev7(i)+1) mod q, for i = 0..127  (Algorithm 11, base-case modulus
               constant, used by base_case_multiply / pointwise multiplication).

Run: python3 scripts/build/gen_twiddle_rom.py
"""

from __future__ import annotations

import datetime
import pathlib
import sys

REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT / "tb" / "golden"))

from params import N, Q, ZETA  # noqa: E402
from primitives import _GAMMA, _ZETA_BITREV  # noqa: E402

OUT = REPO_ROOT / "rtl" / "ntt" / "twiddle_rom.sv"

assert len(_ZETA_BITREV) == 128
assert len(_GAMMA) == 128
assert all(0 <= v < Q for v in _ZETA_BITREV)
assert all(0 <= v < Q for v in _GAMMA)


def rom_body(sig: str, values: list[int]) -> str:
    lines = []
    for i, v in enumerate(values):
        lines.append(f"    {sig}[{i}] = 12'd{v};")
    return "\n".join(lines)


date_utc = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d")

body = f"""`default_nettype none
// rtl/ntt/twiddle_rom.sv
// GENERATED by scripts/build/gen_twiddle_rom.py on {date_utc} UTC from tb/golden/primitives.py
// (ZETA={ZETA}, Q={Q}, N={N}). Do not hand-edit; re-run the generator instead.
//
// ROM_ZETA[i]  = zeta^BitRev7(i) mod q        (FIPS 203 Algorithms 9/10, Section 4.3)
// ROM_GAMMA[i] = zeta^(2*BitRev7(i)+1) mod q   (FIPS 203 Algorithm 11, Section 4.3.1)
// i = 0 is the Appendix A entry (value 1 for ROM_ZETA); the NTT/INTT FSM only ever addresses
// i = 1..127, consistent with the golden model (evidence/phase00/fips203_errata.md
// errata item #1).

module twiddle_rom (
    input  wire [6:0]  addr_i,       // 0..127
    output logic [11:0] zeta_o,      // ROM_ZETA[addr_i]
    output logic [11:0] gamma_o      // ROM_GAMMA[addr_i]
);

  logic [11:0] rom_zeta [0:127];
  logic [11:0] rom_gamma [0:127];

  initial begin
{rom_body("rom_zeta", _ZETA_BITREV)}
{rom_body("rom_gamma", _GAMMA)}
  end

  assign zeta_o  = rom_zeta[addr_i];
  assign gamma_o = rom_gamma[addr_i];

endmodule
`default_nettype wire
"""

OUT.write_text(body)
print(f"wrote {OUT} ({len(_ZETA_BITREV)} zeta + {len(_GAMMA)} gamma entries)")
