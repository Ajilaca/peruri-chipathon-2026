#!/usr/bin/env python3
"""scripts/build/gen_twiddle_rom_half.py

Phase 5M step S6 (evidence/phase05m/test_plan.md V4): generates rtl/arith/twiddle_rom_half.sv from the verified
golden model (tb/golden/primitives.py's _ZETA_BITREV) -- never hand-typed.

  mode_i = 0 (NTT):  zeta_o = zeta^BitRev7(addr) mod q                       (identical to rtl/ntt/twiddle_rom.sv ROM_ZETA)
  mode_i = 1 (INTT): zeta_o = zeta^BitRev7(addr) * 1665 mod q                (1665 = 2^-1 mod q, the per-layer halving)

The file carries no date, so re-running the generator reproduces it byte for byte (checked by tb/phase5m/check_half_rom.py).
Run: python3 scripts/build/gen_twiddle_rom_half.py
"""

from __future__ import annotations

import pathlib
import sys

REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT / "tb" / "golden"))

from params import N, Q, ZETA  # noqa: E402
from primitives import _ZETA_BITREV  # noqa: E402

INV2 = 1665
assert (2 * INV2) % Q == 1
OUT = REPO_ROOT / "rtl" / "arith" / "twiddle_rom_half.sv"

NTT_TABLE = list(_ZETA_BITREV)
INTT_TABLE = [(v * INV2) % Q for v in _ZETA_BITREV]


def render() -> str:
    body = "\n".join(f"    rom_zeta[{i}] = 12'd{v};" for i, v in enumerate(NTT_TABLE + INTT_TABLE))
    return f"""`default_nettype none
`timescale 1ns/1ps
// rtl/arith/twiddle_rom_half.sv
// GENERATED by scripts/build/gen_twiddle_rom_half.py from tb/golden/primitives.py (ZETA={ZETA}, Q={Q}, N={N}).
// Do not hand-edit; re-run the generator instead.
//
// Twiddle ROM of Phase 5M step S6 (INTT without the scaling pass, evidence/phase05m/test_plan.md):
//   mode_i = 0: ROM_ZETA[i]          = zeta^BitRev7(i) mod q          (same entries as rtl/ntt/twiddle_rom.sv)
//   mode_i = 1: ROM_ZETA[i] * 1665   = zeta^BitRev7(i) * 2^-1 mod q   (1665 = 2^-1 mod q; the INTT halves in every layer)
// Entry i = 0 is the Appendix A entry; the FSM only addresses i = 1..127. mode_i is constant during a run.

module twiddle_rom_half (
    input  wire         mode_i,      // 0 = NTT table, 1 = INTT table (zeta / 2)
    input  wire [6:0]   addr_i,      // 0..127
    output logic [11:0] zeta_o
);

  logic [11:0] rom_zeta [0:255];

  initial begin
{body}
  end

  assign zeta_o = rom_zeta[{{mode_i, addr_i}}];

endmodule
`default_nettype wire
"""


if __name__ == "__main__":
    OUT.write_text(render())
    print(f"written {OUT.relative_to(REPO_ROOT)}")
