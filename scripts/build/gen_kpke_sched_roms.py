#!/usr/bin/env python3
"""scripts/build/gen_kpke_sched_roms.py

Phase 6 (evidence/phase06/test_plan.md V3): generates, from the verified golden model (never hand-typed),
  rtl/sched/gamma_rom.sv      gamma_i = zeta^(2*BitRev7(i)+1) mod q, i = 0..127 (tb/golden/primitives.py _GAMMA; FIPS 203 Algorithm 11)
  rtl/sched/kpke_prog_rom.sv  the operation programs of tb/golden/kpke_sched_model.py (PROGRAMS), one 20-bit word per operation
The files carry no date, so re-running reproduces them byte for byte; --check compares instead of writing (exit 1 on a difference).
Usage: python3 scripts/build/gen_kpke_sched_roms.py [--check]
"""
from __future__ import annotations

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tb" / "golden"))

from kpke_sched_model import NPOLY, PROG_ID, PROGRAMS  # noqa: E402
from params import Q, ZETA  # noqa: E402
from primitives import _GAMMA  # noqa: E402

GAMMA_OUT = ROOT / "rtl" / "sched" / "gamma_rom.sv"
PROG_OUT = ROOT / "rtl" / "sched" / "kpke_prog_rom.sv"
PW = 6   # program counter width (longest program 24 operations + END)


def gamma_sv() -> str:
    body = "\n".join(f"      7'd{i:<3}: gamma_o = 12'd{v};" for i, v in enumerate(_GAMMA))
    return f"""`default_nettype none
`timescale 1ns/1ps
// rtl/sched/gamma_rom.sv
// GENERATED by scripts/build/gen_kpke_sched_roms.py from tb/golden/primitives.py (_GAMMA, ZETA={ZETA}, Q={Q}). Do not hand-edit.
// gamma_o = zeta^(2 * BitRev7(addr_i) + 1) mod q: the constant of BaseCaseMultiply for coefficient pair addr_i (FIPS 203 Algorithm 11).

module gamma_rom (
    input  wire  [6:0]  addr_i,
    output logic [11:0] gamma_o
);

  always_comb begin
    case (addr_i)
{body}
      default: gamma_o = 12'd0;
    endcase
  end

endmodule
`default_nettype wire
"""


def prog_sv() -> str:
    lines = []
    for name, pid in PROG_ID.items():
        prog = PROGRAMS[name] + [(0, 0, 0, 0, 0, 0)]
        assert len(prog) <= 2 ** PW
        for pc, (opc, d, a, b, first, last) in enumerate(prog):
            assert max(d, a, b) < NPOLY
            lines.append(f"      {{2'd{pid}, {PW}'d{pc}}}: op_o = {{3'd{opc}, 1'b{first}, 1'b{last}, 5'd{d}, 5'd{a}, 5'd{b}}};"
                         f"   // {name} {pc}")
    body = "\n".join(lines)
    return f"""`default_nettype none
`timescale 1ns/1ps
// rtl/sched/kpke_prog_rom.sv
// GENERATED by scripts/build/gen_kpke_sched_roms.py from tb/golden/kpke_sched_model.py (PROGRAMS). Do not hand-edit.
// Operation word: {{opc[2:0], first, last, dst[4:0], a[4:0], b[4:0]}}; opc 0 END, 1 NTT, 2 INTT, 3 PWM, 4 ADD, 5 SUB.
// Programs: 0 K-PKE.KeyGen arithmetic, 1 K-PKE.Encrypt arithmetic, 2 K-PKE.Decrypt arithmetic. Unlisted addresses return END.

module kpke_prog_rom (
    input  wire  [1:0]    prog_i,
    input  wire  [{PW-1}:0]    pc_i,
    output logic [19:0]   op_o
);

  always_comb begin
    case ({{prog_i, pc_i}})
{body}
      default: op_o = 20'd0;
    endcase
  end

endmodule
`default_nettype wire
"""


def main() -> int:
    check = "--check" in sys.argv
    bad = 0
    for path, text in ((GAMMA_OUT, gamma_sv()), (PROG_OUT, prog_sv())):
        if check:
            same = path.exists() and path.read_text() == text
            print(f"{path.relative_to(ROOT)}: {'reproduced byte for byte' if same else 'DIFFERS'}")
            bad += not same
        else:
            path.write_text(text)
            print(f"written {path.relative_to(ROOT)}")
    if check:
        print(f"gamma entries checked against the golden list: {len(_GAMMA)}")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
