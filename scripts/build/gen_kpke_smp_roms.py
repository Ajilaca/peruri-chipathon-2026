#!/usr/bin/env python3
"""scripts/build/gen_kpke_smp_roms.py

Phase 8c (evidence/phase08/8c/test_plan_8c.md V2): generates rtl/sched/kpke_smp_prog_rom.sv from the verified golden model tb/golden/kpke_smp_model.py (never hand-typed): the programs of the
variants STORE (0), STREAM (1), OVERLAP (2) and STRESS (3, test only), one 21-bit word per operation. The file carries no date, so re-running reproduces it byte for byte; --check compares instead of writing (exit 1 on a difference).
Usage: python3 scripts/build/gen_kpke_smp_roms.py [--check]
"""
from __future__ import annotations

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tb" / "golden"))

from kpke_smp_model import NPOLY, PROG_ID, programs  # noqa: E402

OUT = ROOT / "rtl" / "sched" / "kpke_smp_prog_rom.sv"
PW = 6   # program counter width (longest program: 41 operations + END)


def variants():
    out = []
    for v in (0, 1, 2, 3):
        try:
            out.append((v, programs(v)))
        except NotImplementedError:
            pass
    return out


def prog_sv() -> str:
    lines = []
    for v, progs in variants():
        for name, pid in PROG_ID.items():
            prog = progs[name] + [(0, 0, 0, 0, 0, 0)]
            assert len(prog) <= 2 ** PW
            for pc, (opc, d, a, b, first, last) in enumerate(prog):
                assert max(d, a, b) < max(NPOLY[v], 9) and max(d, a, b) < 32
                lines.append(f"      {{2'd{v}, 2'd{pid}, {PW}'d{pc}}}: op_o = {{4'd{opc}, 1'b{first}, 1'b{last}, 5'd{d}, 5'd{a}, 5'd{b}}};   // var {v} prog {name} {pc}")
    body = "\n".join(lines)
    return f"""`default_nettype none
`timescale 1ns/1ps
// rtl/sched/kpke_smp_prog_rom.sv
// GENERATED by scripts/build/gen_kpke_smp_roms.py from tb/golden/kpke_smp_model.py. Do not hand-edit.
// Operation word: {{opc[3:0], first, last, dst[4:0], a[4:0], b[4:0]}}; opc 0 END, 1 NTT, 2 INTT, 3 PWM, 4 ADD, 5 SUB, 6 SMPN (dst slot, b = counter N, first = non-blocking), 7 SMPA (dst slot, a = matrix index m = 3i + j),
// 8 PWMS (dst, a = matrix index, b, first, last), 9 WAIT. VAR: 0 STORE, 1 STREAM, 2 OVERLAP, 3 STRESS (test only, never synthesised). Programs: 0 KeyGen, 1 Encrypt, 2 Decrypt. Unlisted addresses return END.

module kpke_smp_prog_rom #(
    parameter int VAR = 0
) (
    input  wire  [1:0]    prog_i,
    input  wire  [{PW-1}:0]    pc_i,
    output logic [20:0]   op_o
);

  always_comb begin
    case ({{2'(VAR), prog_i, pc_i}})
{body}
      default: op_o = 21'd0;
    endcase
  end

endmodule
`default_nettype wire
"""


def main() -> int:
    text = prog_sv()
    if "--check" in sys.argv:
        same = OUT.exists() and OUT.read_text() == text
        print(f"{OUT.relative_to(ROOT)}: {'reproduced byte for byte' if same else 'DIFFERS'}")
        return 0 if same else 1
    OUT.write_text(text)
    print(f"written {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
